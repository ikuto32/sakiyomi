// UI translation. The Japanese text is the key; other languages map from it, and
// a missing entry falls back to Japanese. `npm run test:i18n` checks coverage.
import type { NodeView, PvLine, SessionView, Special } from "./api";

export type Lang = "ja" | "en";
export type Notation = "ja" | "western" | "usi";

let current: Lang = "ja";
let notation: Notation = "ja";

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}
export const lang = () => current;
export function setNotation(n: Notation) {
  notation = n;
}
export const currentNotation = () => notation;

export function t(key: string, params?: Record<string, string | number>): string {
  let s = current === "en" ? EN[key] ?? key : key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Side names: 先手/後手, or 下手/上手 in handicap games. */
export function sideName(side: number, handicap = false): string {
  return t(handicap ? (side === 0 ? "下手" : "上手") : side === 0 ? "先手" : "後手");
}

export function playerName(v: SessionView, side: number): string {
  const set = side === 0 ? v.blackName : v.whiteName;
  return set || sideName(side, v.handicap);
}

export function sessionTitle(v: Pick<SessionView, "id" | "title">): string {
  return v.title || t("対局 {n}", { n: v.id });
}

/** KIF names of game-ending events; they double as translation keys. */
